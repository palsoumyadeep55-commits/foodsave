export function getCountryByCode(code: string): CountryInfo | undefined {
  return WORLD_COUNTRIES.find((c) => c.code.toUpperCase() === code.toUpperCase());
}

export function getCountriesByContinent(continent: string): CountryInfo[] {
  if (continent === "All Continents" || !continent) return WORLD_COUNTRIES;
  return WORLD_COUNTRIES.filter((c) => c.continent === continent);
}
